// Score-bar colour band (same thresholds as the PDF's bar fill).
export type ScoreBand = "high" | "mid" | "low" | "fail";

export function scoreBand(score: number): ScoreBand {
  if (score >= 70) return "high";
  if (score >= 60) return "mid";
  if (score >= 40) return "low";
  return "fail";
}

export type ReportCheckRow = {
  id: string;
  name: string; // includes the " · N/A" suffix when the sub-check is N/A
  scoreLabel: string; // "64/100" or "—"
  weightLabel: string; // "15%"
  notes: string;
};

export type ReportDimension =
  | {
      kind: "na";
      id: number;
      name: string;
      note: string;
    }
  | {
      kind: "scored";
      id: number;
      name: string;
      score: number;
      grade: string;
      barPct: number;
      band: ScoreBand;
      checks: ReportCheckRow[];
    };

export type ReportGap = {
  key: string;
  checkName: string;
  dimensionName: string;
  metaLabel: string; // "64/100 · weight 15%"
  finding: string;
  remediation: string;
};

export type AuditReportModel = {
  generatedLabel: string; // "Generated 2026-11-04 12:00:00 UTC · session fb92b10e"
  url: string;
  composite: { score: number; grade: string };
  scopeNote: string;
  executiveSummary: string[]; // sentences, one paragraph each
  dimensions: ReportDimension[];
  gaps: ReportGap[];
  jsonExport: string;
};

export function formatReportTimestamp(ms: number): string {
  return new Date(ms).toISOString().replace("T", " ").replace(/\..+$/, " UTC");
}

function scopeNote(scan: AuditResult["scan"]): string {
  const base = `Scored on ${dimensionCountPhrase(scan.dimensions_applicable, scan.dimensions_scored, scan.dimensions_total)} dimensions applicable to this site.`;
  return base + droppedDimensionsNote(scan);
}

// Every string that can carry site- or model-derived text goes through
// cleanDisplayText: invisible / bidi / control characters stripped, one
// paragraph, length-capped. Rendering then escapes it (renderAuditHtml) or
// React does (AuditReportView). No raw HTML path exists for these fields.
const clean = (s: string | undefined, max?: number) => cleanDisplayText(s ?? "", max);

export function buildAuditReportModel(
  audit: AuditResult,
  sessionId: string,
): AuditReportModel {
  const { scan, gaps } = audit;

  const dimensions: ReportDimension[] = scan.dimensions.map((d) => {
    // Slice 3a: whole-dimension N/A renders as a single explanatory note
    // rather than a sub-check table.
    if (d.na) {
      return {
        kind: "na",
        id: d.dimension_id,
        name: clean(d.dimension_name, 120),
        note: clean(d.sub_checks[0]?.notes ?? AUDIT_REPORT_COPY.naFallbackNote),
      };
    }
    return {
      kind: "scored",
      id: d.dimension_id,
      name: clean(d.dimension_name, 120),
      score: d.score,
      grade: d.grade,
      barPct: Math.max(0, Math.min(100, d.score)),
      band: scoreBand(d.score),
      checks: d.sub_checks.map((s) => ({
        id: s.id,
        name: `${clean(s.name, 120)}${s.na ? ` · ${AUDIT_REPORT_COPY.naLabel}` : ""}`,
        scoreLabel: s.na ? "—" : `${s.score}/100`,
        weightLabel: `${s.weight}%`,
        notes: clean(s.notes),
      })),
    };
  });

  return {
    generatedLabel: `Generated ${formatReportTimestamp(scan.created_at)} · session ${sessionId.slice(0, 8)}`,
    url: clean(scan.url, 300),
    composite: { score: scan.composite.score, grade: scan.composite.grade },
    scopeNote: scopeNote(scan),
    // Deterministic copy, but it interpolates dimension names from the scan.
    executiveSummary: buildExecutiveSummary(audit, AUDIT_REPORT_COPY.gapsHeading).map((s) =>
      clean(s, 2000),
    ),
    dimensions,
    // Lowest score first, as the gaps intro promises. The stored payload is in
    // dimension order (llmEnrichGaps); Array.prototype.sort is stable, so equal
    // scores keep that dimension order.
    gaps: [...gaps]
      .sort((a, b) => a.score - b.score)
      .map((g, i) => ({
      key: `${g.dimension_id}:${g.check_id}:${i}`,
      checkName: clean(g.check_name, 120),
      dimensionName: clean(g.dimension_name, 120),
      metaLabel: `${g.score}/100 · weight ${g.weight}%`,
      finding: clean(g.notes),
      remediation: clean(g.remediation, REMEDIATION_MAX_CHARS),
    })),
    jsonExport: escapeUnsafeInJson(JSON.stringify(audit, null, 2)),
  };
}
