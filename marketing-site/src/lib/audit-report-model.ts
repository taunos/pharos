// Shared view-model for the paid Audit report.
//
// ONE shaping step feeds BOTH renderers:
//   - renderAuditHtml (lib/audit-pipeline.ts) → the PDF
//   - AuditReportView (components/AuditReportView.tsx) → /audit-results/[id]
// so the on-page report and the PDF can never disagree on content, wording or
// ordering. Renderers only add markup/styling; every string a buyer reads
// (headings, labels, notes, score/weight formatting) comes from here.
//
// Pure: no Next, no Worker bindings, no DOM — safe in the Worker pipeline and
// in a client component.

