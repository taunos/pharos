// Score-bar colour band (same thresholds as the PDF's bar fill).
export type ScoreBand = "high" | "mid" | "low" | "fail";

export function scoreBand(score: number): ScoreBand {
  if (score >= 70) return "high";
  if (score >= 60) return "mid";
  if (score >= 40) return "low";
  return "fail";
}

export type ReportCheckRow = {
  id: string;
  name: string; // includes the " · N/A" suffix when the sub-check is N/A
  scoreLabel: string; // "64/100" or "—"
  weightLabel: string; // "15%"
  notes: string;
};

export type ReportDimension =
  | {
      kind: "na";
      id: number;
      name: string;
      note: string;
      unmeasured?: true;
      // dim6:v6: measured but not graded (option A floor or failed checks).
      notGraded?: true;
      // dim6:v6: evidence rows kept under a section with no grade (mix-ups,
      // contradictions), shown after the note.
      evidence?: Array<{ id: string; name: string; notes: string }>;
    }
  | {
      kind: "scored";
      id: number;
      name: string;
      score: number;
      grade: string;
      barPct: number;
      band: ScoreBand;
      checks: ReportCheckRow[];
    };

export type ReportGap = {
  key: string;
  checkName: string;
  dimensionName: string;
  metaLabel: string; // "64/100 · weight 15%"
  finding: string;
  remediation: string;
};

export type AuditReportModel = {
  generatedLabel: string; // "Generated 2026-11-04 12:00:00 UTC · session fb92b10e"
  url: string;
  composite: { score: number; grade: string };
  scopeNote: string;
  versionNote: string;
  executiveSummary: string[]; // sentences, one paragraph each
  dimensions: ReportDimension[];
  gaps: ReportGap[];
  jsonExport: string;
};

export function formatReportTimestamp(ms: number): string {
  return new Date(ms).toISOString().replace("T", " ").replace(/\..+$/, " UTC");
}

// Every string that can carry site- or model-derived text goes through
// cleanDisplayText: invisible / bidi / control characters stripped, one
// paragraph, length-capped. Rendering then escapes it (renderAuditHtml) or
// React does (AuditReportView). No raw HTML path exists for these fields.
const clean = (s: string | undefined, max?: number) => cleanDisplayText(s ?? "", max);

// Sub-check notes as the reader sees them: the plain-language version
// (score-notes.ts). Display only: remediation, the executive summary and the
// JSON export keep reading the raw scanner note.
const shownNote = (id: string, notes: string | undefined) => clean(plainScoreNote({ id, notes: notes ?? "" }));

// Citation Visibility (Dim 6) applies to every site: when it is N/A it was
// not measured (no provider answers, daily cap), never "did not apply".
// Older stored audits don't carry `unmeasured` on it.
const CITATION_DIM_ID = 6;
export function isUnmeasuredDimension(d: { dimension_id: number; na?: boolean; unmeasured?: boolean }): boolean {
  return !!d.na && (!!d.unmeasured || d.dimension_id === CITATION_DIM_ID);
}

// dim6:v6 option A: Citation Visibility measured but not graded (runDim6.ts
// DIM6_NOT_ENOUGH_EVIDENCE_ID / DIM6_CHECKS_FAILED_ID). Read from the stored
// sub-check id, so re-rendered stored audits get it too.
const NOT_GRADED_CHECK_IDS = new Set(["dim6_not_enough_evidence", "dim6_checks_failed"]);
export function isNotGradedDimension(d: { na?: boolean; sub_checks?: Array<{ id: string }> }): boolean {
  return !!d.na && NOT_GRADED_CHECK_IDS.has(d.sub_checks?.[0]?.id ?? "");
}

/** Label and grade text for a whole-dimension N/A, shared by every renderer. */
export function naLabelOf(d: { unmeasured?: boolean; notGraded?: boolean }): string {
  return d.notGraded ? AUDIT_REPORT_COPY.naLabelNotGraded : d.unmeasured ? AUDIT_REPORT_COPY.naLabelUnmeasured : AUDIT_REPORT_COPY.naLabel;
}
export function naGradeOf(d: { unmeasured?: boolean; notGraded?: boolean }): string {
  return d.unmeasured || d.notGraded ? AUDIT_REPORT_COPY.naGradeUnmeasured : AUDIT_REPORT_COPY.naGrade;
}

// dim6:v5: informational rows (na, weight 0) that WERE measured: not "did not
// apply or could not be measured" in the scope line, and no "· N/A" label.
const INFORMATIONAL_CHECK_IDS = new Set([
  "citation_misidentified_answers",
  "citation_contradicted_answers",
  "citation_backed_answers",
  "citation_uncheckable_answers",
]);

function namesList(names: string[]): string {
  if (names.length <= 1) return names.join("");
  return `${names.slice(0, -1).join(", ")} and ${names[names.length - 1]}`;
}

function scopeNote(scan: AuditResult["scan"]): string {
  const C = AUDIT_REPORT_COPY;
  const scored = scan.dimensions.filter((d) => !d.na).length;
  const total = Math.max(scan.dimensions_total ?? 0, scan.dimensions.length);
  const name = (d: { dimension_name: string }) => clean(d.dimension_name, 120);
  const notGraded = scan.dimensions.filter(isNotGradedDimension).map(name);
  const unmeasured = scan.dimensions.filter((d) => isUnmeasuredDimension(d) && !isNotGradedDimension(d)).map(name);
  const inapplicable = scan.dimensions.filter((d) => d.na && !isUnmeasuredDimension(d)).map(name);
  let s = C.scopeScored(scored, total);
  if (inapplicable.length > 0) s += C.scopeNotApplicable(namesList(inapplicable));
  if (unmeasured.length > 0) s += C.scopeNotMeasured(namesList(unmeasured));
  if (notGraded.length > 0) s += C.scopeNotGraded(namesList(notGraded));
  const naChecks = scan.dimensions.filter((d) => !d.na).reduce((n, d) => n + d.sub_checks.filter((sc) => sc.na && !INFORMATIONAL_CHECK_IDS.has(sc.id)).length, 0);
  if (inapplicable.length + unmeasured.length + notGraded.length > 0) {
    s += naChecks > 0 ? `${C.scopeNotCounted.slice(0, -1)}; ${C.scopeChecksNotCounted(naChecks)}` : C.scopeNotCounted;
  } else if (naChecks > 0) {
    s += ` ${C.scopeChecksNotCounted(naChecks)}`;
  }
  return s;
}

function versionNote(scoringVersion: unknown): string {
  const v = reportScoringVersion(scoringVersion);
  return `${v ? `${AUDIT_REPORT_COPY.versionThisReport(v)} ` : ""}${AUDIT_REPORT_COPY.versionNotice}`;
}

export function buildAuditReportModel(
  audit: AuditResult,
  sessionId: string,
): AuditReportModel {
  const { scan } = audit;
  // Only checks that did not pass, highest weighted impact first (older
  // stored audits also listed passing checks scoring below 100).
  const gaps = orderGaps(scan, audit.gaps);

  const dimensions: ReportDimension[] = scan.dimensions.map((d) => {
    // Slice 3a: whole-dimension N/A renders as a single explanatory note
    // rather than a sub-check table.
    if (d.na) {
      return {
        kind: "na",
        id: d.dimension_id,
        name: clean(d.dimension_name, 120),
        note: shownNote(d.sub_checks[0]?.id ?? "", d.sub_checks[0]?.notes ?? AUDIT_REPORT_COPY.naFallbackNote),
        // Applies but was not measured this run: graded "not measured", not
        // "not applicable". Key only present when set (old scans unchanged).
        ...(isUnmeasuredDimension(d) ? { unmeasured: true as const } : {}),
        ...(isNotGradedDimension(d) ? { notGraded: true as const } : {}),
        ...(() => {
          const evidence = isNotGradedDimension(d)
            ? d.sub_checks.slice(1).filter((s) => INFORMATIONAL_CHECK_IDS.has(s.id)).map((s) => ({ id: s.id, name: clean(s.name, 120), notes: shownNote(s.id, s.notes) }))
            : [];
          return evidence.length > 0 ? { evidence } : {};
        })(),
      };
    }
    return {
      kind: "scored",
      id: d.dimension_id,
      name: clean(d.dimension_name, 120),
      score: d.score,
      grade: d.grade,
      barPct: Math.max(0, Math.min(100, d.score)),
      band: scoreBand(d.score),
      checks: d.sub_checks.map((s) => ({
        id: s.id,
        name: `${clean(s.name, 120)}${s.na && !INFORMATIONAL_CHECK_IDS.has(s.id) ? ` · ${AUDIT_REPORT_COPY.naLabel}` : ""}`,
        scoreLabel: s.na ? "—" : `${s.score}/100`,
        weightLabel: `${s.weight}%`,
        notes: shownNote(s.id, s.notes),
      })),
    };
  });

  return {
    generatedLabel: `Generated ${formatReportTimestamp(scan.created_at)} · session ${sessionId.slice(0, 8)}`,
    url: clean(scan.url, 300),
    composite: { score: scan.composite.score, grade: scan.composite.grade },
    scopeNote: scopeNote(scan),
    versionNote: versionNote(scan.scoring_version),
    // Deterministic copy, but it interpolates dimension names from the scan.
    executiveSummary: buildExecutiveSummary({ ...audit, gaps }, AUDIT_REPORT_COPY.gapsHeading).map((s) =>
      clean(s, 2000),
    ),
    dimensions,
    gaps: gaps.map((g, i) => ({
      key: `${g.dimension_id}:${g.check_id}:${i}`,
      checkName: clean(g.check_name, 120),
      dimensionName: clean(g.dimension_name, 120),
      metaLabel: `${g.score}/100 · weight ${g.weight}%`,
      finding: shownNote(g.check_id, g.notes),
      remediation: clean(g.remediation, REMEDIATION_MAX_CHARS),
    })),
    jsonExport: escapeUnsafeInJson(JSON.stringify(audit, null, 2)),
  };
}
